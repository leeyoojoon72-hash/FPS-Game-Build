"""Create an original Minecraft-style block zombie OBJ and flat-color atlas."""
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parent
colors = [(76, 130, 57), (49, 94, 40), (41, 150, 153), (64, 65, 135), (35, 35, 46), (19, 30, 19)]
image = Image.new('RGB', (len(colors)*8, 8))
for i, rgb in enumerate(colors):
    for x in range(i*8, (i+1)*8):
        for y in range(8): image.putpixel((x,y), rgb)
image.save(ROOT/'palette.png')
lines = ['# Original block zombie; generated by build_model.py', 'mtllib zombie.mtl', 'usemtl palette']
for i in range(len(colors)): lines.append(f'vt {(i+.5)/len(colors)} 0.5')
count = 0
def box(name, center, size, material):
    global count
    x,y,z = center; a,b,c = [v/2 for v in size]
    vertices = [(x-a,y-b,z-c),(x+a,y-b,z-c),(x+a,y+b,z-c),(x-a,y+b,z-c),
                (x-a,y-b,z+c),(x+a,y-b,z+c),(x+a,y+b,z+c),(x-a,y+b,z+c)]
    lines.append('o '+name)
    lines.extend('v %.5f %.5f %.5f'%v for v in vertices)
    for face in [(1,4,3,2),(5,6,7,8),(1,5,8,4),(2,3,7,6),(4,8,7,3),(1,2,6,5)]:
        lines.append('f '+' '.join(f'{count+i}/{material+1}' for i in face))
    count += 8
box('head',(0,1.95,0),(.6,.6,.6),0)
box('body',(0,1.2,0),(.6,.9,.3),2)
for side in [-1,1]:
    box('leg',(side*.155,.375,0),(.29,.75,.3),3)
    box('shoe',(side*.155,.08,.03),(.3,.16,.36),4)
    box('sleeve',(side*.45,1.5,.12),(.3,.3,.45),2)
    box('arm',(side*.45,1.5,.6),(.3,.3,.6),0)
    box('eye',(side*.15,2.01,.307),(.12,.075,.02),5)
box('nose',(0,1.91,.33),(.1,.1,.08),1)
box('mouth',(0,1.79,.307),(.27,.055,.02),1)
(ROOT/'zombie.obj').write_text('\n'.join(lines)+'\n')
(ROOT/'zombie.mtl').write_text('newmtl palette\nKd 1 1 1\nmap_Kd palette.png\n')
